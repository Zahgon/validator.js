package jsdate

import (
	"math"
	"testing"
	"unicode/utf16"
)

// TestParse checks Date.parse against values the V8 engine returns with the time zone set to UTC.
func TestParse(t *testing.T) {
	cases := []struct {
		in   string
		want float64
	}{
		{"1", 978307200000},
		{"50", -631152000000},
		{"99", 915148800000},
		{"100", -59011459200000},
		{"2020", 1577836800000},
		{"2020-02-30T00:00:00Z", 1583020800000},
		{"-000000-01-01T00:00:00Z", math.NaN()},
		{"Jan 1 2020 13:00 pm", math.NaN()},
		{"Jan 1 2020 12:00 pm", 1577880000000},
		{"2020-01-01", 1577836800000},
		{"2020-01-01T10:00", 1577872800000},
		{"2020-01-01T10:00:00.123456Z", 1577872800123},
		{"2020-01-01T24:00:00Z", 1577923200000},
		{"2020-01-01T24:00:01Z", math.NaN()},
		{"2020/01/02", 1577923200000},
		{"01/02/2020", 1577923200000},
		{"1/2/3", 1041465600000},
		{"Thu Jan 01 2020 00:00:00 GMT+0000 (Coordinated Universal Time)", 1577836800000},
		{"2020-1-1", 1577836800000},
		{"2020-13-01", math.NaN()},
		{"+002020-01-01", 1577836800000},
		{"-002020-01-01T00:00:00+05:30", -125912295000000},
		{"2020-01-01T00:00:00+0530", 1577817000000},
		{"12:30", math.NaN()},
		{"Jan", math.NaN()},
		{"Jan 5", 978652800000},
		{"5 Jan", 978652800000},
		{"2020 Jan 5", 1578182400000},
		{"Jan 5 10:20:30.5 PM", 978733230500},
		{"foo 2020", 1577836800000},
		{"2020 foo", math.NaN()},
		{"2020-01-01 10:00", 1577872800000},
		{"2020-01-01T10:00:00z", 1577872800000},
		{"Mon, 25 Dec 1995 13:30:00 GMT", 819898200000},
		{"Mon, 25 Dec 1995 13:30:00 +0430", 819882000000},
		{"25 Dec 1995 13:30 GMT-8", 819927000000},
		{"1995-12-25T13:30:00.5-08:00", 819927000500},
		{"Dec 25, 1995", 819849600000},
		{"December 17, 1995 03:24:00", 819170640000},
		{"1995-12-17T03:24:00Z", 819170640000},
		{"2019-02-29", 1551398400000},
		{"2019-02-29T00:00:00Z", 1551398400000},
		{"0", 946684800000},
		{"00", 946684800000},
		{"000", 946684800000},
		{"0000", -62167219200000},
		{"00000", 946684800000},
		{"2020-01-01T", math.NaN()},
		{"T10:00", math.NaN()},
		{"10:00 2020-01-01", 1577872800000},
		{"2020-01-01T10:00:00.Z", math.NaN()},
		{"(comment) Jan 1 2020", 1577836800000},
		{"Jan 1 2020 (comment", 1577836800000},
		{"1 2 3 4", math.NaN()},
		{"2000-01-01T00:00:00.000+24:00", math.NaN()},
		{"999999999", math.NaN()},
		{"1e3", math.NaN()},
		{"  2020-01-01", 1577836800000},
		{"2020-01-01  ", 1577836800000},
		{"٢٠٢٠", math.NaN()},
		{"20200101", math.NaN()},
		{"2020.01.01", 1577836800000},
		{"01.02.2020", 1577923200000},
		{"1.2.2020 10:20", 1577960400000},
		{"Jan 1, 2020 10:20:30 EST", 1577892030000},
		{"2020-06-15 PDT 10:00", 1592240400000},
		{"2020-06-15 10:00 PDT", 1592240400000},
		{"tue 2020-06-15", 1592179200000},
		{"2020-06-15T10:00:00.000Z extra", math.NaN()},
		{"275760-09-13", 8640000000000000},
		{"+275760-09-13T00:00:00Z", 8640000000000000},
		{"+275760-09-13T00:00:00.001Z", math.NaN()},
		{"-271821-04-20T00:00:00Z", -8640000000000000},
		{"-271821-04-19T23:00:00-01:00", -8640000000000000},
		{"Feb 30 2020", 1583020800000},
		{"31 Apr 2021", 1619827200000},
		{"2020-02-30", 1583020800000},
		{"24:00", math.NaN()},
		{"24:00 Jan 1 2020", 1577923200000},
		{"12 am Jan 1 2020", math.NaN()},
		{"Jan 1 2020 12 am", math.NaN()},
		{"Jan 1 2020 0:00 am", 1577836800000},
		{"2020-01-01T10:00:00+00", math.NaN()},
		{"1/1/2020 GMT+0100", 1577833200000},
		{"1/1/2020 10:00 GMT+01:30", 1577867400000},
		{"1/1/2020 10:00 +01:30", 1577867400000},
		{"1/1/2020 10:00 -5", 1577890800000},
		{"1/1/2020 10:00 UTC+5", 1577854800000},
	}
	for _, c := range cases {
		got := Parse(utf16.Encode([]rune(c.in)))
		if got != c.want && !(math.IsNaN(got) && math.IsNaN(c.want)) {
			t.Errorf("Date.parse(%q) = %v, want %v", c.in, got, c.want)
		}
	}
}
